def derive_short(name: str) -> str:
    """无约定简称时推导简称：去后缀取主体，主体超 4 字取前 4 字"""
    body = re.sub(r"(大学|学院|职业技术学院|职业学院|师范专科学校)$", "", name)
    if not body:
        body = name
    return body if len(body) <= 4 else body[:4]


def main():
    out_dir = os.path.dirname(os.path.abspath(__file__))
    out_path = os.path.join(out_dir, "schools-national.sql")

    lines = [
        "-- 全国主要高校（生成自 sql/gen_schools.py，教育部公布的普通高等学校名单主要高校）",
        "-- id 从 s_1001 起，与 schema.sql（s_0001~s_0005）/ mock-data.sql（s_0006~s_0010）不冲突",
        "-- 重复执行安全：INSERT IGNORE 幂等",
        "INSERT IGNORE INTO t_school (id, name, short_name, goods_count, deleted, create_time, update_time) VALUES",
    ]
    rows = []
    for i, (name, short) in enumerate(SCHOOLS, start=1001):
        short_name = short or derive_short(name)
        rows.append(
            f"('s_{i}', '{name}', '{short_name}', 0, 0, NOW(3), NOW(3))"
        )
    lines.append(",\n".join(rows) + ";")
    lines.append("")
    lines.append(f"-- 共 {len(rows)} 所")

    with open(out_path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print(f"已生成 {out_path}，共 {len(rows)} 所高校")


